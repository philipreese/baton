    public static MemoryAddOptions Parse(IReadOnlyList<string> args)
    {
        ArgumentNullException.ThrowIfNull(args);

        string? text = null;
        string? repository = null;
        MemoryKind? kind = null;
        var dryRun = false;
        var help = false;

        var i = 0;
        while (i < args.Count)
        {
            var arg = args[i];
            switch (arg)
            {
                case "--help":
                case "-h":
                    help = true;
                    i++;
                    break;
                case "--dry-run":
                    dryRun = true;
                    i++;
                    break;
                case "--text":
                    text = RequireValue(args, i);
                    i += 2;
                    break;
                case "--kind":
                    kind = ParseKind(RequireValue(args, i));
                    i += 2;
                    break;
                case "--repository":
                    repository = ParseRepository(RequireValue(args, i), Usage);
                    i += 2;
                    break;
                default:
                    throw new CliArgumentException(
                        arg.StartsWith("--", StringComparison.Ordinal)
                            ? $"Unknown option '{arg}'. {Usage}"
                            : $"Unexpected argument '{arg}'. {Usage}");
            }
        }

        if (help)
        {
            // Help is answered before the invocation is adjudicated, the same posture
            // MemorySyncOptionsParser takes: '--help' asks what the verb is, not whether this call is
            // well formed. The kind is a placeholder no code path reads under Help.
            return new MemoryAddOptions(string.Empty, MemoryKind.Unknown, repository, dryRun, Help: true);
        }

        if (text is not { Length: > 0 } || string.IsNullOrWhiteSpace(text))
        {
            throw new CliArgumentException(
                $"'--text' is required and cannot be blank: this verb writes one memory per call and " +
                $"there is nothing here to write. {Usage}",
                "pass the memory itself, for example: --text \"the smoke tasks live outside Baton.slnx\".");
        }

        if (kind is not { } declaredKind)
        {
            throw new CliArgumentException(
                $"'--kind' is required: an added entry's kind is DECLARED by whoever writes it, and " +
                $"nothing here will read your text to guess one. {Usage}",
                $"pass one of: {string.Join(", ", Kinds)}.");
        }

        return new MemoryAddOptions(text, declaredKind, repository, dryRun, Help: false);
    }

    /// <summary>
    /// The declared kind, matched against <see cref="Kinds"/> — the JSON spelling, so what an operator
    /// types is what the store shows.
    /// </summary>
    private static MemoryKind ParseKind(string value)
    {
        foreach (var candidate in Enum.GetValues<MemoryKind>())
        {
            if (candidate != MemoryKind.Unknown &&
                MemoryJsonNames.Of(candidate).Equals(value.Trim(), StringComparison.OrdinalIgnoreCase))
            {
                return candidate;
            }
        }

        throw new CliArgumentException(
            $"'--kind {value}' is not a kind this verb writes. {Usage}",
            value.Trim().Equals(MemoryJsonNames.Of(MemoryKind.Unknown), StringComparison.OrdinalIgnoreCase)
                ? "'unknown' is the absence of a kind, recorded for an imported entry nothing could " +
                  $"establish one for -- it is not a kind you declare. Pass one of: {string.Join(", ", Kinds)}."
                : $"pass one of: {string.Join(", ", Kinds)}.");
    }

    /// <summary>
    /// The subject, canonicalized and then held to the same standard <c>--assert</c> is
    /// (<see cref="MemoryImportOptionsParser.RequireAHostThatAProbeCouldAnswer"/>) — both are WRITE
    /// paths, and a store filed under an identity no git probe could ever answer for is one nothing
    /// will find again. <c>MemorySyncOptionsParser</c>'s own remarks are where the read path states why
    /// it applies only the first half. Shared with <c>MemoryRetractOptionsParser</c> (#2113), which
    /// names the same store file the same way; <paramref name="usage"/> is whichever verb's grammar
    /// the refusal should print.
    /// </summary>
    internal static string ParseRepository(string value, string usage)
    {
        // The reserved word is answered before canonicalization, which would otherwise refuse it as
        // "no host-and-path" -- correct for a git identity and the wrong answer for the one subject that
        // is not one (#2112).
        if (FleetMemory.IsFleet(value))
        {
            return FleetMemory.Slug;
        }

        if (RepositoryIdentity.TryCanonicalize(value) is not { Length: > 0 } canonical)
        {
            throw new CliArgumentException(
                $"'{value.Trim()}' is not a repository identity: it has no host-and-path to " +
                $"canonicalize, so no store file could be named for it. {usage}",
                "pass a canonical identity, for example 'github.com/owner/repo' — a clone URL " +
                "('https://github.com/owner/repo.git', 'git@github.com:owner/repo.git') is accepted " +
                "and normalised to one.");
        }

        MemoryImportOptionsParser.RequireAHostThatAProbeCouldAnswer(value, canonical, usage);
        return canonical;
    }

    private static string RequireValue(IReadOnlyList<string> args, int index)
    {
        if (index + 1 >= args.Count)
        {
            throw new CliArgumentException(
                $"Option '{args[index]}' requires a value. {Usage}",
                $"pass a value after '{args[index]}'.");
        }

        return args[index + 1];
    }
}
